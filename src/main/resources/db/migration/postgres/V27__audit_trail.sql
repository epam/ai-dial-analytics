-- Change tracking for the table catalog: Hibernate Envers revisions + full-state mirrors of the two
-- audited entities, plus the denormalized activity feed derived from them.
--
-- Only table_definition and column_mapping are audited. Since V25 folded the enrichment grain and the
-- MergeTree ordering key into table_definition, an enrichment's grain and a table's ordering are part
-- of the definition row's own history — there is no separate entity, and no separate mirror.
--
-- Every table here is additive: nothing existing changes shape, so there is no backfill. History
-- starts at deployment, and the feed represents that honestly by having no entries before it.

-- One row per transaction that changed an audited entity. `author`/`email` are the caller's identity
-- as it stood at that moment, captured for attribution only and never used to authorize anything.
--
-- IDENTITY rather than Envers' default sequence: that default allocates in blocks of 50, so a
-- hand-written `increment by 1` sequence would hand out ids the application had already used. An
-- identity column sidesteps the question rather than trying to match the allocation size.
-- author/email are TEXT rather than bounded, and deliberately so. Both come from token claims an
-- operator chooses (`security.defaults.principal-claim` and the per-provider overrides), so their
-- length is not ours to predict — and a value that overflowed the column would fail the revision insert
-- at commit, taking the caller's catalog mutation down with it. That is precisely the failure the
-- listener's claim-extraction try/catch exists to prevent, which it cannot help with here because the
-- failure is in persistence, not extraction. TEXT also matches `audit_activity.initiated_author`, which
-- holds a copy of the same value; two widths for one value is a bug waiting for a long principal.
CREATE TABLE revinfo (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp BIGINT NOT NULL,
    author    TEXT,
    email     TEXT
);

-- === Audited entity mirrors ============================================================= --
--
-- Four physical rules govern both tables below. Each fails at RUNTIME rather than at startup, because
-- spring.jpa.hibernate.ddl-auto is `none` and nothing validates the mapping against the schema:
--
--  1. EVERY non-id column is nullable, including those that are NOT NULL in the live table. This is
--     why `write_mode`, `system`, `access`, `ordering_key`, `type`, `status`, `nullable`, `sensitive`,
--     `heavy`, and `ordinal` are all nullable here and not in the original.
--
--     Note this is deliberately NOT justified by "delete rows are all NULL": ADAS sets
--     `org.hibernate.envers.store_data_at_delete`, so a DEL row here carries the entity's final state,
--     which is what makes "what was deleted" answerable and is asserted by an integration test. The
--     nullability is defensive rather than currently load-bearing: that property is a setting, and
--     turning it off would make every DEL row all-NULL and every delete of an audited entity fail at
--     commit against NOT NULL columns. Envers generates its own audit DDL nullable for the same reason.
--  2. `revtype` is SMALLINT on PostgreSQL, holding ADD=0, MOD=1, DEL=2.
--  3. The primary key is (rev, <live pk columns>) — the revision is part of the identity of the row.
--  4. Id components are plain columns carrying the LIVE names. Envers' `originalId` is a
--     mapping-level component name that never reaches SQL, so there is no `original_id` prefix.
--
-- The live tables' foreign keys and CHECK constraints are deliberately NOT carried over. A foreign
-- key would let a delete in a referenced table cascade away history, which is the one thing an audit
-- trail must not permit. A CHECK is dropped because it constrains a *current* row against rules that
-- history is not obliged to satisfy: these tables hold every state a row ever had, including states
-- written before a constraint existed, and (if `store_data_at_delete` is ever disabled) all-NULL delete
-- rows that satisfy nothing. An audit table's job is to record what was, not to re-litigate whether it
-- should have been.

CREATE TABLE table_definition_aud (
    rev                   INTEGER  NOT NULL REFERENCES revinfo (id),
    revtype               SMALLINT,
    name                  TEXT     NOT NULL,
    description           TEXT,
    type                  TEXT,
    source_table          TEXT,
    status                TEXT,
    partition_column      TEXT,
    partition_granularity TEXT,
    system                BOOLEAN,
    access                JSONB,
    tag_order             TEXT[],
    version_column        TEXT,
    identity_column       TEXT,
    ttl_column            TEXT,
    ttl_interval          INTEGER,
    ttl_unit              TEXT,
    write_mode            TEXT,
    grain_key             TEXT,
    ordering_key          TEXT[],
    PRIMARY KEY (rev, name)
);

CREATE TABLE column_mapping_aud (
    rev          INTEGER  NOT NULL REFERENCES revinfo (id),
    revtype      SMALLINT,
    table_name   TEXT     NOT NULL,
    source_name  TEXT     NOT NULL,
    name         TEXT,
    type         TEXT,
    element_type TEXT,
    nullable     BOOLEAN,
    description  TEXT,
    display_name TEXT,
    tag          TEXT,
    sensitive    BOOLEAN,
    heavy        BOOLEAN,
    ordinal      INT,
    PRIMARY KEY (rev, table_name, source_name)
);

-- A snapshot read resolves an entity at a revision with a correlated max(rev) subquery keyed by the
-- entity id, so it reads by id first and revision second — the opposite order to the primary key.
CREATE INDEX table_definition_aud_name_rev_idx ON table_definition_aud (name, rev);
CREATE INDEX column_mapping_aud_table_rev_idx ON column_mapping_aud (table_name, rev);

-- === Activity feed ====================================================================== --
--
-- One row per changed entity per revision, denormalized so the feed is a single-table read: the
-- author and timestamp are copied off the revision rather than joined back to it.
--
-- `parent_activity_id` points at the Table activity of the same revision, letting a client collapse a
-- schema patch's per-column entries under the act that caused them. It is nullable and a NULL is
-- normal, not an error — a column edited without touching its definition row has no parent. It
-- deliberately carries no self-referencing foreign key: the parent is written in the same flush as
-- its children, and an ordering constraint between them would buy nothing an application invariant
-- does not already give.
CREATE TABLE audit_activity (
    activity_id        VARCHAR(36) PRIMARY KEY,
    activity_type      TEXT    NOT NULL,
    resource_type      TEXT    NOT NULL,
    resource_id        TEXT    NOT NULL,
    epoch_timestamp_ms BIGINT  NOT NULL,
    initiated_author   TEXT,
    initiated_email    TEXT,
    parent_activity_id VARCHAR(36),
    revision           INTEGER NOT NULL REFERENCES revinfo (id)
);

-- The four access paths the feed's filters produce: by resource, by time (also the default sort), by
-- parent (the frontend's `in` filter fetching a parent's children), and by revision (retrieving every
-- activity of one administrative act).
--
-- `resource_id` leads its index, not `resource_type`. Every lookup in this shape filters the id — "what
-- happened to this table" — and most send no type at all, and PostgreSQL cannot range-scan a b-tree on
-- a non-leading column. With the type first (two distinct values) the common query would read the whole
-- index; with the id first it seeks, and a query that does send both still uses the second column.
CREATE INDEX audit_activity_resource_idx ON audit_activity (resource_id, resource_type);

-- The timestamp index carries the full ordering the feed emits, because that ordering is always
-- three-column: every activity of one revision shares that revision's timestamp, so the reading layer
-- appends the revision (monotonic across replicas) and then the id to make the order total — without
-- which offset paging repeats and skips rows. An index covering only the leading column would leave the
-- default unfiltered feed — the first call the admin UI makes — sorting a table that by design is never
-- pruned. Ascending serves both directions, since a b-tree can be scanned backwards.
CREATE INDEX audit_activity_timestamp_idx ON audit_activity (epoch_timestamp_ms, revision, activity_id);
CREATE INDEX audit_activity_parent_idx ON audit_activity (parent_activity_id);
CREATE INDEX audit_activity_revision_idx ON audit_activity (revision);
